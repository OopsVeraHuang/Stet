/* Optional developer check: uses an existing Playwright + Chromium installation.
   Creates its own temporary profile; never touches the owner's runtime data. */
const {chromium} = require('playwright');
const {spawn} = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const profile = fs.mkdtempSync(path.join(os.tmpdir(),'continuity-browser-'));
const output = path.join(root,'.local','browser-check');
fs.mkdirSync(output,{recursive:true});
const server = spawn(process.env.CONTINUITY_PYTHON || 'python', ['-m','continuity','--data-dir',profile],{cwd:root,stdio:['ignore','pipe','pipe']});
let browser;
(async()=>{
  const url = await new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(new Error('Local server startup timed out')),10000);
    server.stdout.on('data',data=>{const match=data.toString().match(/http:\/\/127\.0\.0\.1:\d+/);if(match){clearTimeout(timeout);resolve(match[0]);}});
    server.on('error',reject);server.on('exit',code=>{if(code)reject(new Error('Server exited: '+code));});
  });
  browser=await chromium.launch({executablePath:process.env.CONTINUITY_CHROMIUM || '/usr/bin/chromium',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1280,height:1000}});
  const errors=[];const external=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(!r.url().startsWith(url+'/'))external.push(r.url());});
  await page.goto(url);
  await page.getByRole('button',{name:'预览 JSON 示例',exact:true}).click();
  await page.locator('#preview').waitFor({state:'visible'});
  assert.match(await page.locator('#preview-summary').innerText(),/总消息 6/);
  assert.equal((await (await page.request.get(url+'/api/messages')).json()).messages.length,0);
  await page.screenshot({path:path.join(output,'01-import.png'),fullPage:true});
  await page.getByRole('button',{name:'确认导入',exact:true}).click();
  await page.locator('#screen-memory').waitFor({state:'visible'});
  assert.equal(await page.locator('#memory-list .card').count(),6);
  await page.screenshot({path:path.join(output,'02-memory.png'),fullPage:true});
  await page.getByRole('button',{name:'03　原文检索',exact:true}).click();
  await page.locator('#query').fill('松湾');
  await page.getByRole('button',{name:'查找原文',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#search-count').textContent.includes('找到 2'));
  await page.locator('#search-results').getByRole('button',{name:'查看出处'}).first().click();
  await page.locator('#provenance').waitFor({state:'visible'});
  assert.match(await page.locator('#provenance-content').innerText(),/demo-01/);
  assert.match(await page.locator('#provenance-content').innerText(),/\/messages\/0/);
  const downloadEvent=page.waitForEvent('download');
  await page.getByRole('link',{name:'下载完整原文件（原始字节）'}).click();
  const download=await downloadEvent;
  assert.equal(download.suggestedFilename(),'messages.json');
  assert.deepEqual(fs.readFileSync(await download.path()),fs.readFileSync(path.join(root,'examples/messages.json')));
  await page.screenshot({path:path.join(output,'03-provenance.png'),fullPage:true});
  await page.getByRole('button',{name:'关闭',exact:true}).click();
  await page.locator('#query').fill('不存在的虚构词句');
  await page.getByRole('button',{name:'查找原文',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#search-count').textContent.includes('找到 0'));
  await page.getByRole('button',{name:'01　导入',exact:true}).click();
  await page.getByRole('button',{name:'预览 JSON 示例',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#preview-guidance').textContent.includes('已导入'));
  assert.equal(await page.locator('#confirm-import').isDisabled(),true);
  await page.getByRole('button',{name:'预览 MD 示例',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#preview-title').textContent.includes('messages.md'));
  await page.getByRole('button',{name:'确认导入',exact:true}).click();
  await page.locator('#screen-memory').waitFor({state:'visible'});
  assert.equal(await page.locator('#memory-list .card').count(),10);
  await page.locator('#branch-filter').selectOption(JSON.stringify('alternative'));
  assert.equal(await page.locator('#memory-list .card').count(),1);
  assert.match(await page.locator('#memory-list').innerText(),/还不知道/);
  await page.locator('#branch-filter').selectOption('*');
  await page.getByRole('button',{name:'重建检索索引',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('重建 10'));
  // A file error must clear the previous preview and prevent stale confirmation.
  await page.getByRole('button',{name:'01　导入',exact:true}).click();
  const bad={messages:[{id:'bad',source_id:'synthetic',conversation_id:'c',role:'human',recorded_at:'yesterday',text:'invented'}]};
  await page.locator('#file').setInputFiles({name:'bad.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(bad))});
  await page.waitForFunction(()=>document.querySelector('#preview-title').textContent.includes('bad.json'));
  assert.equal(await page.locator('#confirm-import').isDisabled(),true);
  assert.match(await page.locator('#preview-rows').innerText(),/角色不受支持/);
  // Imported markup must remain inert plain text in both cards and the dialog.
  const malicious={messages:[{id:'markup',source_id:'synthetic-markup',conversation_id:'c',role:'user',text:'<img src=x onerror="window.__injected=true"> <script>window.__injected=true</script>'}]};
  await page.locator('#file').setInputFiles({name:'markup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(malicious))});
  await page.waitForFunction(()=>document.querySelector('#preview-title').textContent.includes('markup.json'));
  assert.equal(await page.locator('#preview-rows img,#preview-rows script').count(),0);
  await page.getByRole('button',{name:'确认导入',exact:true}).click();
  await page.locator('#screen-memory').waitFor({state:'visible'});
  assert.equal(await page.evaluate(()=>window.__injected),undefined);
  await page.locator('summary').filter({hasText:'管理已导入的文件'}).click();
  await page.getByRole('button',{name:'撤销整批导入',exact:true}).first().click();
  await page.getByRole('button',{name:'保留',exact:true}).click();
  assert.equal((await (await page.request.get(url+'/api/messages')).json()).messages.length,11);
  for(let i=0;i<3;i++) {
    await page.getByRole('button',{name:'撤销整批导入',exact:true}).first().click();
    await page.getByRole('button',{name:'确认撤销整批',exact:true}).click();
    await page.locator('#remove-dialog').waitFor({state:'hidden'});
    await page.waitForFunction(n=>document.querySelectorAll('#batches .batch').length===n,2-i);
  }
  assert.equal((await (await page.request.get(url+'/api/messages')).json()).messages.length,0);
  await page.getByRole('button',{name:'重建检索索引',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('重建 0'));
  await page.reload();
  await page.getByRole('button',{name:'02　记忆',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('#memory-count').textContent.includes('0 / 0'));
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'01　导入',exact:true}).click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(output,'04-narrow.png'),fullPage:true});
  assert.deepEqual(errors,[]);assert.deepEqual(external,[]);
  console.log('PASS: JSON/MD preview, commit, duplicates, branch filter, source download, literal search, invalid input, inert markup, rebuild, cancel/delete, reload, narrow layout; no external requests.');
  console.log('Synthetic screenshots: '+output);
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill();await new Promise(resolve=>{if(server.exitCode!==null)resolve();else server.on('exit',resolve);});fs.rmSync(profile,{recursive:true,force:true});});
